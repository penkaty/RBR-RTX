#!/usr/bin/env python3
"""Writes remix_defaults.inc: the Remix default value of every simple option, for the F3 "Remix settings" page.

Source: RtxOptions.md of the Remix runtime the add-on ships with (RBR-RTX-remixplus; Remix writes it itself with
DXVK_DOCUMENTATION_WRITE_RTX_OPTIONS_MD=1). Run again after the runtime changes:

    python gen_remix_defaults.py <path to RtxOptions.md> [remix_defaults.inc]

Hash lists, virtual keys and other list-like options are left out (the page does not edit them).
"""
import re
import sys

SKIP_TYPES = {"hash set", "hash vector", "virtual keys"}


def unescape(text):
    return re.sub(r"\\(.)", r"\1", text)


def main():
    src = sys.argv[1]
    dst = sys.argv[2] if len(sys.argv) > 2 else "remix_defaults.inc"
    rows = {}
    for line in open(src, encoding="utf-8"):
        if not line.startswith("|rtx."):
            continue
        parts = line.rstrip("\n").split("|")
        if len(parts) < 4:
            continue
        key, typ, default = parts[1], parts[2], unescape(parts[3]).strip()
        if typ in SKIP_TYPES or "<br>" in default or len(default) > 80:
            continue
        rows[key] = default
    with open(dst, "w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by gen_remix_defaults.py from RtxOptions.md (%d options). Sorted by key; do not edit.\n" % len(rows))
        for key in sorted(rows):
            out.write('{ "%s", "%s" },\n' % (key, rows[key].replace("\\", "\\\\").replace('"', '\\"')))
    print("%d options -> %s" % (len(rows), dst))


if __name__ == "__main__":
    main()
